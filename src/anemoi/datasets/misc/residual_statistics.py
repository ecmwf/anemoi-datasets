"""The residual-statistics file: shared format, writer and reader.

Warnings
--------

Experimental: the file format, the ``residual_statistics`` option and the
``residual_statistics`` attribute may be removed or renamed in a future
release.

*Residual statistics* are the statistics of the difference ``dsA - dsB`` between
two datasets. They are produced by::

    anemoi-datasets compute <dsA> --minus <dsB> --output-statistics residual.npz

and consumed by::

    open_dataset(..., residual_statistics="residual.npz").residual_statistics

Both sides use this module so that the format cannot drift apart.

The file is a **compressed numpy archive** (``.npz``): one ``float64`` array per
statistic, named ``<block>.<statistic>``, and everything else -- the header, the
variable names, the provenance -- as a JSON string in a single
:data:`METADATA_KEY` entry. NaN is stored as NaN in the arrays; the JSON string
maps it to ``null``, as JSON has no NaN. See :func:`save` and
:func:`load_document`. The keys that identify and describe the document are:

``kind``
    :data:`RESIDUAL_KIND` for a residual-statistics file. Plain (non-residual)
    statistics written by the same command carry :data:`STATISTICS_KIND`
    instead, so a file of the wrong kind is rejected rather than silently used.
``version``
    Format version, see :data:`VERSION`. A reader refuses a version it does not
    know about.
``datasets``
    The two dataset labels the residual was computed from, in the order they
    were subtracted: the residual is ``datasets[0] - datasets[1]``.
``variables``
    The variable names, indexing the statistics arrays.
``statistics``
    One array per key of :data:`STATISTICS_KEYS`, with one value per variable in
    the order given by ``variables``, stored as ``statistics.<key>``.

``derived_from``
    How the statistics were produced: the ``open_dataset`` call(s) the values
    came from, the arithmetic applied to them, the anemoi-datasets version and
    the command line. The same entry a dataset generated by the ``compute``
    command carries, so a statistics file and the dataset written beside it
    describe themselves the same way. Optional: files written before it existed
    do not have it.

Other keys (``tendency``, ``tendency_statistics``, ``compare``, ...) may be
present; they are ignored by the reader but kept by the writer.
"""

import json
import logging
import os
from typing import Any

import numpy as np
from numpy.typing import NDArray

LOG = logging.getLogger(__name__)

#: ``kind`` marker of a residual-statistics file.
RESIDUAL_KIND = "residual-statistics"

#: ``kind`` marker of a plain (non-residual) statistics file.
STATISTICS_KIND = "statistics"

#: Current format version.
VERSION = 1

#: The statistics the file is expected to carry, one value per variable.
STATISTICS_KEYS = ("mean", "stdev", "minimum", "maximum")

#: Extension that selects the numpy-archive format instead of JSON.
NPZ_SUFFIX = ".npz"

#: Name of the npz entry holding everything in the document that is not an
#: array, as a JSON string.
METADATA_KEY = "metadata"

#: The blocks of the document stored as arrays in an npz file. Each of their
#: statistics is one entry, named ``<block>.<statistic>``.
ARRAY_BLOCKS = ("statistics", "tendency_statistics")


class ResidualStatisticsNotAvailable(AttributeError):
    """Raised when a dataset has no residual statistics attached.

    Subclasses :class:`AttributeError` so that ``getattr(ds,
    "residual_statistics", None)`` and friends behave as expected.
    """


def header(kind: str, datasets: list[str]) -> dict[str, Any]:
    """Build the identifying header of a statistics document.

    Parameters
    ----------
    kind : str
        Either :data:`RESIDUAL_KIND` or :data:`STATISTICS_KIND`.
    datasets : list of str
        The dataset labels the statistics were computed from: for a residual,
        the two datasets in the order they were subtracted (the residual is
        ``datasets[0] - datasets[1]``); otherwise the single dataset.

    Returns
    -------
    dict
        The ``kind``, ``version`` and ``datasets`` keys to merge into the
        document.
    """
    assert kind in (RESIDUAL_KIND, STATISTICS_KIND), kind
    if kind == RESIDUAL_KIND and len(datasets) != 2:
        raise ValueError(f"A residual needs exactly two datasets, got {datasets}")
    return dict(kind=kind, version=VERSION, datasets=list(datasets))


def _jsonable(obj: Any) -> Any:
    """Recursively convert numpy arrays/scalars to plain Python, mapping NaN to ``None``.

    JSON has no NaN, so the writer maps it to ``null`` and the reader maps it
    back; the two must stay in step.
    """
    if isinstance(obj, np.ndarray):
        return [None if (isinstance(x, float) and np.isnan(x)) else x for x in obj.tolist()]
    if isinstance(obj, (np.floating, np.integer)):
        return _jsonable(obj.item())
    if isinstance(obj, dict):
        return {k: _jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_jsonable(v) for v in obj]
    if isinstance(obj, float) and np.isnan(obj):
        return None
    return obj


def check_path(path: "str | os.PathLike[str]") -> str:
    """Return ``path`` as a string, checking that it names a numpy archive.

    Parameters
    ----------
    path : str or path-like
        The path to check.

    Returns
    -------
    str
        The path.

    Raises
    ------
    ValueError
        If it does not end with :data:`NPZ_SUFFIX`.
    """
    path = os.fspath(path)
    if not path.endswith(NPZ_SUFFIX):
        raise ValueError(f"A statistics file must end with '{NPZ_SUFFIX}', got '{path}'")
    return path


def save(path: "str | os.PathLike[str]", document: dict[str, Any]) -> None:
    """Write a statistics document as a compressed numpy archive.

    The statistics of :data:`ARRAY_BLOCKS` become ``float64`` arrays, one entry
    per statistic, named ``<block>.<statistic>``; NaN is kept as NaN. Everything
    else -- the header, the variable names, the provenance, and any other key of
    the document -- is kept as a JSON string in the :data:`METADATA_KEY` entry, so
    that the archive is self-describing and ``np.load(path)["metadata"]`` gives
    back the whole of it.

    Parameters
    ----------
    path : str or path-like
        Where to write the document. Must end with :data:`NPZ_SUFFIX`.
    document : dict
        The document to write, as built by the ``compute`` command.
    """
    path = check_path(path)

    arrays: dict[str, NDArray[Any]] = {}
    metadata: dict[str, Any] = {}

    for key, value in document.items():
        if key in ARRAY_BLOCKS and value is not None:
            for name, values in value.items():
                arrays[f"{key}.{name}"] = np.asarray(values, dtype=np.float64)
        else:
            metadata[key] = _jsonable(value)

    arrays[METADATA_KEY] = np.array(json.dumps(metadata, indent=2))
    np.savez_compressed(path, **arrays)


def load_document(path: "str | os.PathLike[str]") -> dict[str, Any]:
    """Read a statistics document written by :func:`save`.

    Parameters
    ----------
    path : str or path-like
        The numpy archive to read.

    Returns
    -------
    dict
        The document, with the array blocks turned back into lists of values.
    """
    path = check_path(path)
    if not os.path.exists(path):
        raise FileNotFoundError(f"No such statistics file: {path}")

    try:
        archive = np.load(path, allow_pickle=False)
    except Exception as e:  # noqa: BLE001 - numpy raises several unrelated types here
        raise ValueError(f"{path}: not a valid numpy archive ({e})") from e

    with archive:
        if METADATA_KEY not in archive.files:
            raise ValueError(f"{path}: not an anemoi statistics archive (no '{METADATA_KEY}' entry)")
        try:
            document = json.loads(str(archive[METADATA_KEY].item()))
        except json.JSONDecodeError as e:
            raise ValueError(f"{path}: the '{METADATA_KEY}' entry is not valid JSON ({e})") from e
        if not isinstance(document, dict):
            raise ValueError(f"{path}: the '{METADATA_KEY}' entry must be an object, got {type(document).__name__}")

        for block in ARRAY_BLOCKS:
            prefix = f"{block}."
            values = {name[len(prefix) :]: archive[name].tolist() for name in archive.files if name.startswith(prefix)}
            if values:
                # The arrays win, but anything the metadata happens to carry under
                # the same block is kept: a statistic that is not a plain list of
                # numbers can only live there.
                block_values = document.get(block)
                document[block] = {**block_values, **values} if isinstance(block_values, dict) else values

    return document


class ResidualStatisticsFile:
    """A validated residual-statistics file.

    Attributes
    ----------
    path : str
        Where the file was read from.
    kind : str
        Always :data:`RESIDUAL_KIND` (a file of another kind is refused at load
        time).
    version : int
        The format version of the file.
    datasets : list of str
        The two dataset labels the residual was computed from.
    variables : list of str
        The variable names indexing the statistics.
    provenance : dict or None
        The file's ``derived_from`` entry, or ``None`` when it has none.
    """

    def __init__(self, path: str, document: dict[str, Any]) -> None:
        """Validate ``document`` as a residual-statistics file.

        Parameters
        ----------
        path : str
            The path the document was read from, used in error messages and
            metadata.
        document : dict
            The document, as returned by :func:`load_document`.

        Raises
        ------
        ValueError
            If the document is not a valid residual-statistics file.
        """
        self.path = str(path)

        if not isinstance(document, dict):
            raise ValueError(f"{self.path}: expected an object, got {type(document).__name__}")

        self.kind = document.get("kind")
        if self.kind != RESIDUAL_KIND:
            if self.kind == STATISTICS_KIND:
                raise ValueError(
                    f"{self.path}: this file holds plain statistics, not residual statistics. "
                    f"Recompute it with `anemoi-datasets compute <dataset-a> "
                    f"--minus <dataset-b>`."
                )
            raise ValueError(
                f"{self.path}: not a residual-statistics file (expected kind={RESIDUAL_KIND!r}, got kind={self.kind!r})"
            )

        self.version = document.get("version")
        if not isinstance(self.version, int) or isinstance(self.version, bool):
            raise ValueError(f"{self.path}: missing or invalid 'version' ({self.version!r})")
        if self.version > VERSION:
            raise ValueError(
                f"{self.path}: format version {self.version} is newer than the supported "
                f"version {VERSION}; please upgrade anemoi-datasets."
            )

        datasets = document.get("datasets")
        if not isinstance(datasets, (list, tuple)) or len(datasets) != 2:
            raise ValueError(f"{self.path}: 'datasets' must be a list of the two dataset names, got {datasets!r}")
        if not all(isinstance(d, str) and d for d in datasets):
            raise ValueError(f"{self.path}: 'datasets' must be a list of two non-empty names, got {datasets!r}")
        self.datasets = [str(d) for d in datasets]

        variables = document.get("variables")
        if not isinstance(variables, (list, tuple)) or not variables:
            raise ValueError(f"{self.path}: 'variables' must be a non-empty list, got {variables!r}")
        if not all(isinstance(v, str) for v in variables):
            raise ValueError(f"{self.path}: 'variables' must be a list of names, got {variables!r}")
        self.variables = [str(v) for v in variables]

        duplicates = sorted({v for v in self.variables if self.variables.count(v) > 1})
        if duplicates:
            raise ValueError(f"{self.path}: duplicated variables {duplicates}")

        # Optional: files written before 'derived_from' existed have none, and
        # nothing here depends on it.
        provenance = document.get("derived_from")
        self.provenance = provenance if isinstance(provenance, dict) else None

        self._index = {name: i for i, name in enumerate(self.variables)}
        self._arrays = self._parse_statistics(document.get("statistics"))

    def _parse_statistics(self, statistics: Any) -> dict[str, NDArray[np.float64]]:
        """Validate and convert the ``statistics`` block to float64 arrays."""
        if not isinstance(statistics, dict):
            raise ValueError(f"{self.path}: 'statistics' must be an object, got {statistics!r}")

        missing = [k for k in STATISTICS_KEYS if k not in statistics]
        if missing:
            raise ValueError(f"{self.path}: 'statistics' is missing {missing}")

        result = {}
        for key in STATISTICS_KEYS:
            values = statistics[key]
            if not isinstance(values, (list, tuple)):
                raise ValueError(f"{self.path}: statistics['{key}'] must be a list, got {values!r}")
            if len(values) != len(self.variables):
                raise ValueError(
                    f"{self.path}: statistics['{key}'] has {len(values)} values "
                    f"but there are {len(self.variables)} variables"
                )
            # The arrays keep NaN as NaN; 'null' is only what the JSON metadata
            # string uses for it, and is tolerated here too.
            result[key] = np.array([np.nan if v is None else float(v) for v in values], dtype=np.float64)
        return result

    @classmethod
    def load(cls, path: "str | os.PathLike[str]") -> "ResidualStatisticsFile":
        """Read and validate a residual-statistics file.

        Parameters
        ----------
        path : str or path-like
            Path to the ``.npz`` file.

        Returns
        -------
        ResidualStatisticsFile
            The validated file.
        """
        path = os.fspath(path)
        return cls(path, load_document(path))

    def select(self, variables: list[str]) -> dict[str, NDArray[np.float64]]:
        """Return the statistics for ``variables``, in that order.

        Parameters
        ----------
        variables : list of str
            The variables to extract, typically a dataset's ``variables``. The
            file may hold more variables than requested, but not fewer.

        Returns
        -------
        dict
            Mapping of :data:`STATISTICS_KEYS` to arrays indexed like
            ``variables``.
        """
        unknown = [v for v in variables if v not in self._index]
        if unknown:
            raise ValueError(
                f"{self.path}: no residual statistics for variable(s) {unknown}; the file has {self.variables}"
            )
        index = np.array([self._index[v] for v in variables], dtype=int)
        return {k: v[index] for k, v in self._arrays.items()}

    def metadata(self) -> dict[str, Any]:
        """Return the provenance of this file, for the dataset metadata.

        Only the two scalars of ``derived_from`` that identify *when* and *by
        which version* the file was written are surfaced here: this ends up in
        the metadata of every dataset the file is attached to, and from there in
        training checkpoints, so the whole entry would be too much.
        """
        result = dict(
            path=self.path,
            kind=self.kind,
            version=self.version,
            datasets=list(self.datasets),
            variables=list(self.variables),
        )
        if self.provenance is not None:
            result["anemoi_datasets_version"] = self.provenance.get("anemoi_datasets_version")
            result["created"] = self.provenance.get("created")
        return result

    def __repr__(self) -> str:
        return f"{self.__class__.__name__}({self.path}, {' - '.join(self.datasets)})"
